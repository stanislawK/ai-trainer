import uuid

from sqlalchemy import (
    CheckConstraint,
    Computed,
    ForeignKey,
    Index,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import ARRAY
from sqlalchemy.orm import Mapped, mapped_column

from ai_trainer.adapters.orm.base import Base


class ExerciseOrm(Base):
    """A shared catalogue row, or an athlete's custom exercise when `owner_user_id` is set
    (ADR-0031). Catalogue rows hold no user data."""

    __tablename__ = "exercises"
    __table_args__ = (
        UniqueConstraint("source", "source_ref", name="exercises_source_source_ref_key"),
        CheckConstraint("source <> 'custom' OR owner_user_id IS NOT NULL", name="exercises_owner"),
        CheckConstraint("char_length(name) BETWEEN 1 AND 200", name="exercises_name_length"),
        CheckConstraint(
            "default_measure IN ('load_reps', 'reps', 'time', 'distance', 'band_reps')",
            name="exercises_default_measure",
        ),
        Index(
            "ix_exercises_name_trgm",
            text("exercise_name_norm(name) gin_trgm_ops"),
            postgresql_using="gin",
        ),
        Index(
            "ix_exercises_name_tsv",
            text("to_tsvector('simple', exercise_name_norm(name))"),
            postgresql_using="gin",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    # A `SportRegistry` ID stored as text, never a database enum (ADR-0006).
    sport_id: Mapped[str] = mapped_column(Text, nullable=False)
    owner_user_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=True, index=True
    )
    source: Mapped[str] = mapped_column(Text, nullable=False)
    source_ref: Mapped[str | None] = mapped_column(Text, nullable=True)
    name: Mapped[str] = mapped_column(Text, nullable=False)
    equipment: Mapped[str | None] = mapped_column(Text, nullable=True)
    body_part: Mapped[str | None] = mapped_column(Text, nullable=True)
    target: Mapped[str | None] = mapped_column(Text, nullable=True)
    secondary_muscles: Mapped[list[str] | None] = mapped_column(ARRAY(Text), nullable=True)
    default_measure: Mapped[str] = mapped_column(Text, nullable=False)
    attribution: Mapped[str | None] = mapped_column(Text, nullable=True)


class ExerciseTextOrm(Base):
    """An exercise's imported description in one language (ADR-0031, G5)."""

    __tablename__ = "exercise_texts"

    # The key's first column, so it indexes `exercise_id` too.
    exercise_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("exercises.id", ondelete="CASCADE"), primary_key=True
    )
    lang: Mapped[str] = mapped_column(Text, primary_key=True)
    instructions: Mapped[str] = mapped_column(Text, nullable=False)
    steps: Mapped[list[str]] = mapped_column(ARRAY(Text), nullable=False)


class ExerciseAliasOrm(Base):
    """Another name for an exercise: global when `user_id` is NULL, otherwise learned from that
    athlete (ADR-0031). `alias_norm` is generated by the same SQL function a lookup calls, so a
    stored alias and a typed name can't normalize differently."""

    __tablename__ = "exercise_aliases"
    __table_args__ = (
        CheckConstraint("char_length(alias) BETWEEN 1 AND 200", name="exercise_aliases_length"),
        CheckConstraint("alias_norm <> ''", name="exercise_aliases_norm_present"),
        # Also indexes `user_id` for the account deletion's cascade.
        Index(
            "exercise_aliases_user_alias_key",
            "user_id",
            "alias_norm",
            unique=True,
            postgresql_where=text("user_id IS NOT NULL"),
        ),
        Index(
            "exercise_aliases_global_alias_key",
            "exercise_id",
            "alias_norm",
            unique=True,
            postgresql_where=text("user_id IS NULL"),
        ),
        Index(
            "ix_exercise_aliases_alias_norm_trgm",
            text("alias_norm gin_trgm_ops"),
            postgresql_using="gin",
        ),
        Index(
            "ix_exercise_aliases_alias_tsv",
            text("to_tsvector('simple', alias_norm)"),
            postgresql_using="gin",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    exercise_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("exercises.id", ondelete="CASCADE"), nullable=False, index=True
    )
    user_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=True
    )
    alias: Mapped[str] = mapped_column(Text, nullable=False)
    alias_norm: Mapped[str] = mapped_column(
        Text, Computed("exercise_name_norm(alias)", persisted=True), nullable=False
    )
    lang: Mapped[str | None] = mapped_column(Text, nullable=True)
